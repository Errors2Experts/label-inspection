"""
PDF builder for inspection reports (ReportLab).

Pure ReportLab, no Django imports. It takes the plain dict produced by
reports.services.build_report_context(), the same data the HTML preview
uses, so the PDF and the on-screen report always match.
Layout follows the approved LabelInspect report design.
"""
import io
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import cm
from reportlab.lib.utils import ImageReader
from reportlab.platypus import (
    HRFlowable,
    Image as RLImage,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

MAX_IMAGES = 6

DISCLAIMER = (
    "Generated by LabelInspect · Errors2Experts · "
    "This is an inspection-assistance report. Not a laboratory certificate."
)

TEAL = colors.HexColor('#0f766e')
GREY = colors.HexColor('#64748b')
LINE = colors.HexColor('#e2e8f0')
INK = colors.HexColor('#0f172a')

# result -> (background, border, text)
RESULT_STYLES = {
    'COMPLIANT': ('#f0fdf4', '#bbf7d0', '#15803d'),
    'NON_COMPLIANT': ('#fef2f2', '#fecaca', '#b91c1c'),
    'REQUIRES_VERIFICATION': ('#fffbeb', '#fde68a', '#b45309'),
    'NOT_APPLICABLE': ('#f1f5f9', '#cbd5e1', '#475569'),
}


def _styles():
    base = getSampleStyleSheet()
    body = ParagraphStyle('body', parent=base['Normal'], fontSize=9.5, leading=14, textColor=INK)
    return {
        'title': ParagraphStyle('title', parent=body, fontName='Helvetica-Bold', fontSize=20,
                                leading=24, alignment=1, textColor=TEAL),
        'sub': ParagraphStyle('sub', parent=body, fontSize=10, alignment=1, textColor=GREY),
        'h': ParagraphStyle('h', parent=body, fontName='Helvetica-Bold', fontSize=11,
                            spaceBefore=12, spaceAfter=2),
        'body': body,
        'small': ParagraphStyle('small', parent=body, fontSize=8.5, textColor=GREY),
        'cap': ParagraphStyle('cap', parent=body, fontSize=8, textColor=GREY, alignment=1),
    }


def _clean(text):
    # Built-in Helvetica has no rupee glyph; print "Rs." in the PDF instead.
    return escape(str(text).replace('₹', 'Rs. '))


def _p(text, style):
    return Paragraph(_clean(text).replace('\n', '<br/>'), style)


def _inline(pairs, bold_labels=False):
    parts = []
    for label, value in pairs:
        lab = f"<b>{_clean(label)}:</b>" if bold_labels else f"{_clean(label)}:"
        parts.append(f"{lab} {_clean(value)}")
    return ' · '.join(parts)


def _heading(text, st):
    return [
        Paragraph(_clean(text), st['h']),
        HRFlowable(width='100%', thickness=0.6, color=LINE, spaceBefore=1, spaceAfter=5),
    ]


def _scaled_image(path, max_w, max_h):
    iw, ih = ImageReader(path).getSize()
    scale = min(max_w / iw, max_h / ih, 1)
    return RLImage(path, width=iw * scale, height=ih * scale)


def _evidence_table(images, st, width):
    cell_w = width / 2 - 0.3 * cm
    cells = []
    for img in images[:MAX_IMAGES]:
        try:
            pic = _scaled_image(img['path'], cell_w, 5.5 * cm)
        except Exception:
            continue  # missing / unreadable file: skip rather than fail the report
        cells.append([pic, _p(img['label'], st['cap'])])
    if not cells:
        return None

    rows = []
    for i in range(0, len(cells), 2):
        row = list(cells[i:i + 2])
        if len(row) == 1:
            row.append('')
        rows.append(row)

    t = Table(rows, colWidths=[width / 2, width / 2])
    t.setStyle(TableStyle([
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
    ]))
    return t


def _footer(ctx):
    def draw(canvas, doc):
        canvas.saveState()
        canvas.setFont('Helvetica', 7.5)
        canvas.setFillColor(GREY)
        canvas.drawCentredString(A4[0] / 2, 1.3 * cm, DISCLAIMER)
        canvas.drawCentredString(A4[0] / 2, 0.8 * cm, f"{ctx['report_number']} · Page {doc.page}")
        canvas.restoreState()
    return draw


def build_pdf(ctx):
    """Return the report PDF as bytes."""
    st = _styles()
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
        topMargin=1.8 * cm, bottomMargin=2.2 * cm,
        title=f"Inspection Report {ctx['report_number']}",
        author='LabelInspect',
    )
    width = A4[0] - 4 * cm
    story = []

    # Title block
    story += [
        _p('LabelInspect', st['title']),
        _p('Food Label Inspection Report', st['sub']),
        Spacer(1, 6),
        HRFlowable(width='100%', thickness=1.5, color=TEAL, spaceAfter=10),
    ]

    # Inspection / inspector grid
    def block(rows):
        html = '<br/>'.join(_inline([r], bold_labels=True) for r in rows)
        return Paragraph(html, st['body'])

    grid = Table([[block(ctx['header_left']), block(ctx['header_right'])]],
                 colWidths=[width * 0.5, width * 0.5])
    grid.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
    ]))
    story.append(grid)

    # Product information
    story += _heading('Product Information', st)
    title = f"<b>{_clean(ctx['product_title'])}</b>"
    if ctx['product_meta1']:
        title += ' · ' + _inline(ctx['product_meta1'])
    story.append(Paragraph(title, st['body']))
    if ctx['product_meta2']:
        story.append(Paragraph(_inline(ctx['product_meta2']), st['body']))

    # Verified label data
    story += _heading('Verified Label Data', st)
    for line in ctx['label_lines']:
        story.append(Paragraph(_inline(line), st['body']))

    # Compliance result
    story += _heading('Compliance Result', st)
    bg, border, fg = RESULT_STYLES.get(ctx['result'], RESULT_STYLES['NOT_APPLICABLE'])
    fg_hex = fg
    box = Table([[[
        Paragraph(f"<font color='{fg_hex}'><b>{_clean(ctx['result_label'].upper())}</b></font>",
                  ParagraphStyle('rl', parent=st['body'], fontSize=12, leading=16)),
        Spacer(1, 2),
        Paragraph(_clean(ctx['summary_text']), st['body']),
    ]]], colWidths=[width])
    box.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor(bg)),
        ('BOX', (0, 0), (-1, -1), 0.8, colors.HexColor(border)),
        ('LEFTPADDING', (0, 0), (-1, -1), 10),
        ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ('TOPPADDING', (0, 0), (-1, -1), 8),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
    ]))
    story.append(box)

    # Rule summary
    if ctx['rule_summary']:
        story += _heading('Rule Summary', st)
        story.append(Paragraph(_clean(ctx['rule_summary']), st['small']))

    # Violations (only when present)
    if ctx['violations']:
        story += _heading('Violations', st)
        for v in ctx['violations']:
            line = v['rule'] + (f" — {v['message']}" if v.get('message') else '')
            story.append(Paragraph(f"• {_clean(line)}", st['body']))

    # Remarks (only when present)
    if ctx['remarks']:
        story += _heading('Inspector Remarks', st)
        story.append(_p(ctx['remarks'], st['body']))

    # Evidence (only when present)
    evidence = _evidence_table(ctx['images'], st, width)
    if evidence is not None:
        story += _heading('Evidence Images', st)
        story.append(evidence)

    doc.build(story, onFirstPage=_footer(ctx), onLaterPages=_footer(ctx))
    return buf.getvalue()